import { describe, expect, it } from 'vitest'
import { renderMarkdown } from './markdown'
import { generateDocsHtml } from './docs'
import { newCollection, newFolder, newKeyValue, newRequest, newRequestItem } from './factory'
import { exportPostmanCollection, importPostmanCollection } from './postman'

describe('markdown', () => {
  it('renders common syntax', () => {
    const html = renderMarkdown(
      '# Title\n\nSome **bold**, *italic*, `code` and [a link](https://x.io?a=1&b=2).\n\n- one\n- two\n\n1. first\n\n```json\n{"a": 1}\n```\n\n> quoted\n\n| A | B |\n|---|---|\n| 1 | `x` |'
    )
    expect(html).toContain('<h1>Title</h1>')
    expect(html).toContain('<p>Some <strong>bold</strong>, <em>italic</em>, <code>code</code> and <a href="https://x.io?a=1&amp;b=2" rel="noopener noreferrer">a link</a>.</p>')
    expect(html).toContain('<ul><li>one</li><li>two</li></ul>')
    expect(html).toContain('<ol><li>first</li></ol>')
    expect(html).toContain('<pre><code class="language-json">{&quot;a&quot;: 1}</code></pre>')
    expect(html).toContain('<blockquote><p>quoted</p></blockquote>')
    expect(html).toContain('<table><thead><tr><th>A</th><th>B</th></tr></thead><tbody><tr><td>1</td><td><code>x</code></td></tr></tbody></table>')
  })

  it('neutralises HTML and unsafe links', () => {
    const html = renderMarkdown('<script>alert(1)</script> [x](javascript:alert(1)) <img src=x onerror=alert(1)>')
    expect(html).not.toMatch(/<script|<img|href="javascript/i)
    expect(html).toContain('&lt;script&gt;')
  })
})

describe('docs page', () => {
  const c = newCollection('Shop API')
  c.description = 'Public **shop** endpoints.'
  c.auth = { type: 'bearer', token: '{{token}}' }
  c.variables = [newKeyValue('baseUrl', 'https://api.shop.io')]
  const folder = newFolder('Orders')
  folder.description = 'Everything about orders.'
  folder.items = [
    newRequestItem(
      newRequest({
        name: 'Create order',
        method: 'POST',
        url: '{{baseUrl}}/orders',
        description: 'Creates an order. Returns `201`.',
        params: [{ ...newKeyValue('dryRun', 'true'), enabled: false, description: 'Validate only' }],
        body: { mode: 'raw', raw: '{"sku":"A1","qty":2}', language: 'json' },
        examples: [{ id: 'e', name: 'Created', status: 201, statusText: 'Created', headers: [['Content-Type', 'application/json']], body: '{"id":"o_1"}' }]
      })
    ),
    newRequestItem(newRequest({ name: '<b>Evil</b>', url: '{{baseUrl}}/x', auth: { type: 'none' } }))
  ]
  c.items = [folder, newRequestItem(newRequest({ name: 'Live feed', protocol: 'websocket', url: 'wss://api.shop.io/feed', message: '{"subscribe":"orders"}' }))]

  it('documents collection, folders and requests with inherited auth and examples', () => {
    const html = generateDocsHtml(c, { subtitle: 'Production', generatedAt: new Date('2026-01-02T00:00:00Z') })
    expect(html).toMatch(/^<!doctype html>/)
    expect(html).toContain('<title>Shop API — API documentation</title>')
    expect(html).toContain('<p>Public <strong>shop</strong> endpoints.</p>')
    expect(html).toContain('<code>{{baseUrl}}</code></td><td><code>https://api.shop.io</code>')
    expect(html).toContain('Everything about orders.')
    expect(html).toContain('<span class="method m-post">POST</span> Create order')
    expect(html).toContain('Bearer token <code>{{token}}</code> <span class="tag">inherited</span>')
    expect(html).toContain('<code>dryRun</code> <span class="tag">optional</span>')
    expect(html).toContain('{\n  &quot;sku&quot;: &quot;A1&quot;,\n  &quot;qty&quot;: 2\n}')
    expect(html).toContain('<span class="status s2">201</span> Created')
    expect(html).toContain('&lt;b&gt;Evil&lt;/b&gt;')
    expect(html).toContain('<span class="method m-ws">WS</span> Live feed')
    expect(html).toContain('Generated by ApiMan on 2026-01-02')
  })

  it('keeps descriptions through Postman export/import', () => {
    const back = importPostmanCollection(exportPostmanCollection(c))
    expect(back.description).toBe(c.description)
    const f = back.items[0]
    if (f.type !== 'folder' || f.items[0].type !== 'request') throw new Error('shape')
    expect(f.description).toBe('Everything about orders.')
    expect(f.items[0].request.description).toBe('Creates an order. Returns `201`.')
  })
})
